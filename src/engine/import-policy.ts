/**
 * 読み込みで、手元に同じidで中身の違う資産がある時の扱い。
 * - `rename`: 手元を残し、読み込んだ側を新しいidと別名で足す
 * - `overwrite`: 手元を読み込んだ側で置き換える（idは同じまま）。組み込みと同じidの資産は置き換えられないので、別名で足す
 * - `skip`: 読み込まない（手元を残す）
 * 別のidで足せない種類（組み込みのテキストの読みの直し・個人速度・解析設定）は、`rename`を`skip`として扱う。
 */
export type ImportPolicy = 'rename' | 'overwrite' | 'skip';
