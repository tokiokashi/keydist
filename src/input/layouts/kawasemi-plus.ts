/**
 * かわせみ配列+。
 *
 * 正本:
 *   semialt/kawasemi `plus` branch
 *   `Kikyo/かわせみ配列+.kky`
 *   source blob: c844edd43dbcd00cd0c0bc768c3f59879d1c0179
 *
 * DvorakJ版の「かわせみ配列改」は2022年版で、二重母音拡張までは持つが、
 * Kikyo版にある左右親指の「く・き」「つ・ち」拡張を持たないため、配字はKikyo版を採用する。
 * ただしKikyoの出力表現はDvorakJ版に合わせて `，→、`、`．→。`、`－→ー`、
 * `va/vi/vu/ve/vo→ヴァ/ヴィ/ヴ/ヴェ/ヴォ` と正規化している。
 *
 * KikyoはJIS物理配列なので、ANSIに存在しない各段末尾の専用キーは除外する。
 * 数字・英数記号・括弧マクロなど解析対象外の出力も除外し、かな・長音・日本語句読点を移植する。
 *
 * 同じ出力に複数の打ち方が定義されている場合、keydistのLayoutは代替Sequenceを持てないため、
 * 同時押しの押下キー数が最少の定義を採る。同数ならKikyoファイルで先に現れる定義を採る。
 */
type SourceFace = {
  trigger: readonly string[];
  entries: Readonly<Record<string, string>>;
  options?: Pick<Face, 'layer' | 'inputRole' | 'triggerPersistence'>;
};

function sourceFace(
  trigger: readonly string[],
  entries: Readonly<Record<string, string>>,
  options?: SourceFace['options'],
): SourceFace {
  return { trigger, entries, options };
}

function selectShortestFaces(sources: readonly SourceFace[]): Face[] {
  type Winner = { faceIndex: number; key: string; presses: number };
  const winners = new Map<string, Winner>();

  for (const [faceIndex, source] of sources.entries()) {
    for (const [key, output] of Object.entries(source.entries)) {
      const presses = new Set([...source.trigger, key]).size;
      const current = winners.get(output);
      if (current === undefined || presses < current.presses) {
        winners.set(output, { faceIndex, key, presses });
      }
    }
  }

  const faces: Face[] = [];
  for (const [faceIndex, source] of sources.entries()) {
    const entries = Object.fromEntries(
      Object.entries(source.entries).filter(([key, output]) => {
        const winner = winners.get(output);
        return winner?.faceIndex === faceIndex && winner.key === key;
      }),
    );
    if (Object.keys(entries).length === 0) continue;

    faces.push({
      ...faceFromEntries(source.trigger, 'simultaneous', entries),
      ...source.options,
    });
  }
  return faces;
}

